#!/usr/bin/env bash
# CA2 Part 1: store the Bookstore H2 database in the synced folder.
# Idempotent: it rewrites the same file on every run.
set -euo pipefail

DB_DIR="${DB_DIR:-/home/vagrant/h2-data}"
DB_NAME="${DB_NAME:-bookstore}"
CONFIG_DIR="${CONFIG_DIR:-/home/vagrant/config}"

log() { echo "[configure_db] $*"; }

# The data must live in the synced folder, otherwise it dies with the VM
if [ ! -d "$DB_DIR" ]; then
  log "ERROR: $DB_DIR does not exist (synced folder not mounted)"
  exit 1
fi
if ! sudo -u vagrant test -w "$DB_DIR"; then
  log "ERROR: $DB_DIR is not writable by the vagrant user"
  exit 1
fi

install -d -o vagrant -g vagrant "$CONFIG_DIR"
cat > "$CONFIG_DIR/application.properties" <<EOF
# Generated by provisioning/configure_db.sh - do not edit by hand
spring.datasource.url=jdbc:h2:file:${DB_DIR}/${DB_NAME};DB_CLOSE_ON_EXIT=FALSE
spring.jpa.hibernate.ddl-auto=update
EOF
chown vagrant:vagrant "$CONFIG_DIR/application.properties"

log "H2 database file: ${DB_DIR}/${DB_NAME}.mv.db"
log "Config written to $CONFIG_DIR/application.properties"